export function findInstituteById(id: string): InstituteData | undefined {
  return OFFICIAL_INSTITUTES.find((inst) => inst.id === id);
}

export function isApprovedDomainForInstitute(instituteId: string, emailOrDomain: string): boolean {
  const institute = findInstituteById(instituteId);
  if (!institute) return false;
  const domain = emailOrDomain.includes("@") ? emailOrDomain.split("@").pop()?.toLowerCase() : emailOrDomain.toLowerCase();
  if (!domain) return false;
  return institute.domains.some((d) => domain === d || domain.endsWith(`.${d}`));
}
